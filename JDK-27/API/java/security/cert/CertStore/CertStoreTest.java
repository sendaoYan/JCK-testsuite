    static byte[] fromB64(String s) { return Base64.getMimeDecoder().decode(s); }
    static java.security.cert.X509Certificate fixtureCert(String b64) throws Exception {
        return (java.security.cert.X509Certificate) java.security.cert.CertificateFactory.getInstance("X.509")
            .generateCertificate(new java.io.ByteArrayInputStream(fromB64(b64)));
    }
    static java.security.cert.X509CRL fixtureCrl() throws Exception {
        return (java.security.cert.X509CRL) java.security.cert.CertificateFactory.getInstance("X.509")
            .generateCRL(new java.io.ByteArrayInputStream(fromB64(ROOT_CRL_B64)));
    }

    // ---- Part 2: black-box (behavioral) ----
    static void testBlackBox() throws Exception {

        // Collection-backed store: certificates and CRLs by selector
        X509Certificate root = fixtureCert(ROOT_CERT_B64);
        X509Certificate leaf = fixtureCert(LEAF_CERT_B64);
        X509CRL crl = fixtureCrl();
        List<Object> content = new ArrayList<>();
        content.add(root);
        content.add(leaf);
        content.add(crl);
        CertStore store = CertStore.getInstance("Collection", new CollectionCertStoreParameters(content));
        check(store.getType().equals("Collection"), "type");
        check(store.getCertStoreParameters() instanceof CollectionCertStoreParameters, "params class");
        check(store.getProvider() != null, "provider");
        // all selectors: null selector matches everything
        check(store.getCertificates(null).size() == 2, "null selector all certs");
        check(store.getCRLs(null).size() == 1, "null selector all crls");
        // a null-selector result is an independent copy, not a live view of the store
        store.getCertificates(null).clear();
        check(store.getCertificates(null).size() == 2, "returned collection is a copy");
        // target by subject
        X509CertSelector sel = new X509CertSelector();
        sel.setSubject(root.getSubjectX500Principal());
        Collection<? extends Certificate> found = store.getCertificates(sel);
        check(found.size() == 1 && found.iterator().next().equals(root), "subject selector");
        sel.setSubject(leaf.getSubjectX500Principal());
        check(store.getCertificates(sel).iterator().next().equals(leaf), "leaf selector");
        // CRL by issuer
        X509CRLSelector csel = new X509CRLSelector();
        csel.addIssuer(root.getIssuerX500Principal());
        check(store.getCRLs(csel).size() == 1, "issuer crl selector");
        csel.setIssuers(List.of(leaf.getIssuerX500Principal()));
        check(store.getCRLs(csel).isEmpty(), "no crl for other issuer");
        // factory variants and errors
        check(CertStore.getInstance("Collection",
            new CollectionCertStoreParameters(content), store.getProvider()).getType().equals("Collection"), "provider factory");
        try { CertStore.getInstance("Collection", new CollectionCertStoreParameters(content), "NoSuchProvider"); check(false, "unknown provider"); }
        catch (NoSuchProviderException e) { check(true, "unknown provider NoSuchProviderException"); }
        try { CertStore.getInstance("BOGUS", new CollectionCertStoreParameters()); check(false, "unknown type"); }
        catch (NoSuchAlgorithmException e) { check(true, "unknown type NoSuchAlgorithmException"); }
        try { CertStore.getInstance("LDAP", new CollectionCertStoreParameters()); check(false, "wrong params"); }
        catch (java.security.InvalidAlgorithmParameterException iape) { check(true, "wrong params InvalidAlgorithmParameterException"); }
        try { CertStore.getDefaultType(); check(true, "default type callable"); } catch (Exception e) { check(false, "default type"); }

    }

