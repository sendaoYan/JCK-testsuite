/*
 * @test
 * @summary java.awt.MenuContainer conformance: white-box structure + black-box behavior.
 * @run main MenuContainerTest
 */

import java.lang.reflect.*;

public class MenuContainerTest {
    static int passed;
    static void check(boolean c, String m) { if (!c) throw new AssertionError(m); passed++; }
    static boolean hasMethod(Class<?> c, String n) {
        for (Method m : c.getDeclaredMethods()) if (m.getName().equals(n)) return true;
        return false;
    }
    static boolean hasInterface(Class<?> c, String n) {
        for (Class<?> i : c.getInterfaces()) if (i.getName().equals(n)) return true;
        return false;
    }

    static void testWhiteBox() throws Exception {
        Class<?> c = Class.forName("java.awt.MenuContainer", false, MenuContainerTest.class.getClassLoader());
        check(c != null, "type loads: java.awt.MenuContainer");
        int m = c.getModifiers();
        check(Modifier.isPublic(m) || Modifier.isProtected(m) || c.isMemberClass(), "public/protected/member");
        if (c.isEnum()) check(c.getEnumConstants() != null, "enum has constants");
        else check(c.getEnumConstants() == null, "non-enum returns null constants");
        check(c.getDeclaredConstructors() != null, "constructors array non-null");
        check(c.getDeclaredMethods() != null, "methods array non-null");
        check(c.getDeclaredFields() != null, "fields array non-null");
        if (c.isInterface()) check(Modifier.isInterface(m), "interface modifier consistent");
        else if (c != Object.class) check(c.getSuperclass() != null, "class superclass non-null");
        check(c.isInterface(), "is interface");
    }

    static void testBlackBox() throws Exception {
        java.awt.MenuContainer impl = new java.awt.MenuContainer() {
            public java.awt.Font getFont() { return null; }
            public void remove(java.awt.MenuComponent c) {}
            public boolean postEvent(java.awt.Event e) { return false; }
        };
        check(impl.getFont() == null, "getFont null");
        impl.remove(null);
        check(impl.postEvent(null) == false, "postEvent false");
    }

    public static void main(String[] args) throws Exception {
        testWhiteBox();
        testBlackBox();
        System.out.println("PASS (" + passed + " assertions)");
    }
}
