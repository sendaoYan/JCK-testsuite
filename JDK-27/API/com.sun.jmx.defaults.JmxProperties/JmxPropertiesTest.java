/*
 * @test
 * @summary com.sun.jmx.defaults.JmxProperties conformance: internal package reflection.
 * @modules java.management/com.sun.jmx.defaults:+open
 * @run main JmxPropertiesTest
 */

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

public class JmxPropertiesTest {
    static int passed;
    static void check(boolean c, String m) { if (!c) throw new AssertionError(m); passed++; }

    static String[] methods(Class<?> c) {
        List<String> l = new ArrayList<>();
        for (Method m : c.getDeclaredMethods()) {
            int mod = m.getModifiers();
            if (Modifier.isPublic(mod) || Modifier.isProtected(mod)) l.add(m.getName());
        }
        String[] a = l.toArray(new String[0]); Arrays.sort(a); return a;
    }

    static String[] fields(Class<?> c) {
        List<String> l = new ArrayList<>();
        for (Field f : c.getDeclaredFields()) {
            int mod = f.getModifiers();
            if (Modifier.isPublic(mod) || Modifier.isProtected(mod)) l.add(f.getName());
        }
        String[] a = l.toArray(new String[0]); Arrays.sort(a); return a;
    }

    static String[] enumConstants(Class<?> c) {
        List<String> l = new ArrayList<>();
        for (Field f : c.getDeclaredFields()) {
            if (f.isEnumConstant()) l.add(f.getName());
        }
        String[] a = l.toArray(new String[0]); Arrays.sort(a); return a;
    }

    static String[] interfaces(Class<?> c) {
        List<String> l = new ArrayList<>();
        for (Class<?> i : c.getInterfaces()) l.add(i.getName());
        String[] a = l.toArray(new String[0]); Arrays.sort(a); return a;
    }

    public static void main(String[] args) throws Exception {
        Class<?> c = Class.forName("com.sun.jmx.defaults.JmxProperties", false, JmxPropertiesTest.class.getClassLoader());
        check(c.getName().equals("com.sun.jmx.defaults.JmxProperties"), "name");
        check(c.isInterface() == false, "isInterface");
        check(c.isEnum() == false, "isEnum");
        check(c.isAnnotation() == false, "isAnnotation");
        check(Modifier.isAbstract(c.getModifiers()) == false, "abstract");
        check(Modifier.isFinal(c.getModifiers()) == false, "final");
        check(c.getSuperclass().getName().equals("java.lang.Object"), "superclass");
        check(Arrays.equals(interfaces(c), new String[]{}), "interfaces");
        check(Arrays.equals(methods(c), new String[]{}), "methods");
        check(Arrays.equals(fields(c), new String[]{"JMX_IMPL_NAME","JMX_IMPL_VENDOR","JMX_IMPL_VERSION","JMX_INITIAL_BUILDER","JMX_SPEC_NAME","JMX_SPEC_VENDOR","JMX_SPEC_VERSION","MBEANSERVER_LOGGER","MBEANSERVER_LOGGER_NAME","MISC_LOGGER","MISC_LOGGER_NAME","MODELMBEAN_LOGGER","MODELMBEAN_LOGGER_NAME","MONITOR_LOGGER","MONITOR_LOGGER_NAME","NOTIFICATION_LOGGER","NOTIFICATION_LOGGER_NAME","RELATION_LOGGER","RELATION_LOGGER_NAME","TIMER_LOGGER","TIMER_LOGGER_NAME"}), "fields");
        check(Arrays.equals(enumConstants(c), new String[]{}), "enumConstants");
        System.out.println("PASS (" + passed + " assertions)");
    }
}
