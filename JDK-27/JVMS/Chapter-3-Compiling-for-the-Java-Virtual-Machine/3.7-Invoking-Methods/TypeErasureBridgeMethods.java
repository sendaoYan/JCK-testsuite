/*
 * @test
 * @summary JVMS 3.7/4.7: generic types are erased into their bounds in the
 *          bytecode descriptors (a T field becomes Object) while the Signature
 *          attribute retains the type variable, and a class implementing
 *          Comparable<T> gains a synthetic bridge method compareTo(Object).
 * @run main TypeErasureBridgeMethods
 */

import java.lang.reflect.Field;
import java.lang.reflect.Method;

public class TypeErasureBridgeMethods {
    static int passed = 0;

    static void check(boolean cond, String msg) {
        if (!cond) throw new AssertionError(msg);
        passed++;
    }

    static class Holder<T> {
        T value;
        public T get() { return value; }
    }

    static class Item implements Comparable<Item> {
        int id;
        Item(int id) { this.id = id; }
        public int compareTo(Item o) { return Integer.compare(id, o.id); }
    }

    public static void main(String[] args) throws Exception {
        // Erasure: the field descriptor is Object, not T.
        Field f = Holder.class.getDeclaredField("value");
        check(f.getType() == Object.class, "generic field erases to Object");

        // Signature attribute: the type variable is preserved generically.
        Method get = Holder.class.getMethod("get");
        check("T".equals(get.getGenericReturnType().getTypeName()),
                "Signature attribute preserves the type variable");

        // Bridge method generated by the compiler for Comparable<Item>.
        int bridge = 0;
        int exact = 0;
        for (Method m : Item.class.getDeclaredMethods()) {
            if (m.getName().equals("compareTo")) {
                if (m.isSynthetic() && m.isBridge()
                        && m.getParameterTypes()[0] == Object.class) {
                    bridge++;
                } else if (!m.isBridge()
                        && m.getParameterTypes()[0] == Item.class) {
                    exact++;
                }
            }
        }
        check(bridge == 1, "synthetic bridge compareTo(Object) generated");
        check(exact == 1, "exact compareTo(Item) present");

        System.out.println("PASS (" + passed + " assertions)");
    }
}
